"""Write a C source file that holds the bytes of a file.

    embed_file.py INPUT OUTPUT SYMBOL

defines `const char SYMBOL[]`, the bytes of INPUT followed by a NUL, and
`const size_t SYMBOL_len`, their number without the NUL. cxl-fmd serves
its own schema and registry files from them: nothing is read from disk at
run time.
"""

import sys
from pathlib import Path


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    src, out, sym = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3]
    data = src.read_bytes()
    lines = [
        "/* Generated by scripts/embed_file.py from %s: do not edit */" % src.name,
        "#include <stddef.h>",
        "",
        "extern const char %s[];" % sym,
        "extern const size_t %s_len;" % sym,
        "",
        "const char %s[] = {" % sym,
    ]
    for i in range(0, len(data), 12):
        lines.append("\t" + " ".join("0x%02x," % b for b in data[i:i + 12]))
    lines.append("\t0x00")
    lines.append("};")
    lines.append("const size_t %s_len = %d;" % (sym, len(data)))
    out.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
